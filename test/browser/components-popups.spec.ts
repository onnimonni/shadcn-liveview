test("phoenix sheet: side panels remain inside the viewport and close back to their trigger", async ({ page }) => {
  for (const side of ["right", "left", "top", "bottom"] as const) {
    await openFixture(page, side === "right" ? "sheet-closed" : `sheet-${side}`)
    const trigger = page.getByRole("button", { name: "Edit profile", exact: true })
    if (side === "right") await trigger.click()
    const sheet = page.getByRole("dialog", { name: "Edit profile" })
    await expectUsablePopup(page, sheet, 200, 70)
    await expect(sheet).toContainText("Make changes to your profile here.")
    await expect.poll(async () => {
      const box = await sheet.boundingBox()
      if (!box) return false
      const viewport = page.viewportSize()!
      return side === "right" ? Math.abs(box.x + box.width - viewport.width) <= 1 :
        side === "left" ? Math.abs(box.x) <= 1 :
        side === "top" ? Math.abs(box.y) <= 1 : Math.abs(box.y + box.height - viewport.height) <= 1
    }).toBe(true)
    await sheet.getByRole("button", { name: side === "right" ? "Close" : "Done", exact: true }).click()
    await expect(sheet).toHaveCount(0)
    await expect(trigger).toBeFocused()
  }
})

