import { expect, test, type Locator, type Page } from "@playwright/test"
import { openFixture } from "./component-helpers"

async function expectUsablePopup(page: Page, popup: Locator, minimumWidth = 80, minimumHeight = 24) {
  await expect(popup).toBeVisible()
  // Opening transitions may temporarily translate panels outside the viewport.
  await expect.poll(async () => {
    const box = await popup.boundingBox()
    const viewport = page.viewportSize()!
    return !!box && box.width >= minimumWidth && box.height >= minimumHeight &&
      box.x >= -1 && box.y >= -1 && box.x + box.width <= viewport.width + 1 &&
      box.y + box.height <= viewport.height + 1
  }).toBe(true)
}

test("phoenix accordion: single and multiple disclosure preserve keyboard navigation and disabled boundaries", async ({ page }) => {
  await openFixture(page, "accordion-closed")
  const introduction = page.getByRole("button", { name: "Introduction", exact: true })
  const details = page.getByRole("button", { name: "Details", exact: true })
  await expect(introduction).toHaveAttribute("aria-expanded", "false")
  await introduction.click()
  await expect(page.getByRole("region", { name: "Introduction" })).toHaveText("Start with an introduction.")
  await page.keyboard.press("ArrowDown")
  await expect(details).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(details).toHaveAttribute("aria-expanded", "true")
  await expect(introduction).toHaveAttribute("aria-expanded", "false")
  await expect(page.getByRole("region", { name: "Details" })).toHaveText("Read the details.")
  await details.click()
  await expect(details).toHaveAttribute("aria-expanded", "false")
  await expect(page.getByRole("region")).toHaveCount(0)

  await openFixture(page, "accordion-multiple")
  await page.getByRole("button", { name: "Details", exact: true }).click()
  for (const name of ["Introduction", "Details", "Advanced"]) {
    await expect(page.getByRole("button", { name, exact: true })).toHaveAttribute("aria-expanded", "true")
  }
  await page.getByRole("button", { name: "Introduction", exact: true }).click()
  await expect(page.getByRole("button", { name: "Introduction", exact: true })).toHaveAttribute("aria-expanded", "false")
  await expect(page.getByRole("button", { name: "Details", exact: true })).toHaveAttribute("aria-expanded", "true")

  await openFixture(page, "accordion-disabled")
  const enabledRoot = page.locator("#accordion-disabled-demo")
  await expect(enabledRoot.getByRole("button", { name: "Details", exact: true })).toBeDisabled()
  await enabledRoot.getByRole("button", { name: "Introduction", exact: true }).focus()
  await page.keyboard.press("ArrowDown")
  await expect(enabledRoot.getByRole("button", { name: "Advanced", exact: true })).toBeFocused()
  for (const trigger of await page.locator("#accordion-disabled-root button").all()) await expect(trigger).toBeDisabled()
})

