import { expect, test, type Page } from "@playwright/test"
import { openFixture } from "./component-helpers"

async function formEntries(page: Page, selector: string) {
  return page.locator(selector).evaluate((form: HTMLFormElement) => Array.from(new FormData(form).entries()))
}

test("phoenix checkbox: mouse and keyboard toggles update successful external-form values", async ({ page }) => {
  await openFixture(page, "checkbox-multiple-external-form")
  const read = page.getByRole("checkbox", { name: "Read", exact: true })
  const write = page.getByRole("checkbox", { name: "Write", exact: true })
  await expect(read).toBeChecked()
  await expect(write).not.toBeChecked()
  expect(await formEntries(page, "#checkbox-external")).toEqual([["permissions[]", "read"]])
  await write.click()
  await expect(write).toHaveAttribute("phx-value-state", "checked")
  await expect(write).toBeChecked()
  expect(await formEntries(page, "#checkbox-external")).toEqual([["permissions[]", "read"], ["permissions[]", "write"]])
  await write.press("Space")
  await expect(write).toHaveAttribute("phx-value-state", "unchecked")
  await expect(write).not.toBeChecked()
  await expect(read).toBeChecked()
  expect(await formEntries(page, "#checkbox-external")).toEqual([["permissions[]", "read"]])

  await openFixture(page, "checkbox-indeterminate-enabled")
  const mixed = page.getByRole("checkbox", { name: "Permission" })
  await expect(mixed).toHaveAttribute("aria-checked", "mixed")
  expect(await formEntries(page, "#checkbox-indeterminate-enabled-form")).toEqual([])
  await mixed.press("Space")
  await expect(mixed).toHaveAttribute("phx-value-state", "checked")
  await expect(mixed).toBeChecked()
  expect(await formEntries(page, "#checkbox-indeterminate-enabled-form")).toEqual([["permission", "allow"]])
})

test("phoenix switch: independent sizes toggle and reset their visual and submitted state", async ({ page }) => {
  await openFixture(page, "switch-multiple-external-form")
  const mail = page.getByRole("switch", { name: "Mail", exact: true })
  const sms = page.getByRole("switch", { name: "SMS", exact: true })
  await expect(mail).toBeChecked()
  await expect(sms).not.toBeChecked()
  const mailBox = (await mail.boundingBox())!
  const smsBox = (await sms.boundingBox())!
  expect(mailBox.width).toBeGreaterThanOrEqual(24)
  expect(mailBox.width).toBeLessThanOrEqual(60)
  expect(smsBox.width).toBeGreaterThanOrEqual(20)
  expect(smsBox.width).toBeLessThan(mailBox.width)
  expect(smsBox.height).toBeGreaterThanOrEqual(12)
  await mail.press("Space")
  await expect(mail).toHaveAttribute("phx-value-state", "unchecked")
  await sms.click()
  await expect(sms).toHaveAttribute("phx-value-state", "checked")
  await expect(mail).not.toBeChecked()
  await expect(sms).toBeChecked()
  expect(await formEntries(page, "#switch-settings")).toEqual([["sms", "on"]])
  await page.locator("#switch-settings").evaluate((form: HTMLFormElement) => form.reset())
  await expect(mail).toHaveAttribute("phx-value-state", "checked")
  await expect(sms).toHaveAttribute("phx-value-state", "unchecked")
  await expect(mail).toBeChecked()
  await expect(sms).not.toBeChecked()
  await expect.poll(() => formEntries(page, "#switch-settings")).toEqual([["mail", "on"]])
})

test("phoenix slider: usable tracks preserve keyboard focus, step values, bounds and form entries", async ({ page }) => {
  await openFixture(page, "slider-external-form")
  const slider = page.locator("#slider-external")
  const thumb = slider.getByRole("slider")
  const track = (await slider.boundingBox())!
  expect(track.width).toBeGreaterThanOrEqual(180)
  expect(track.width).toBeLessThanOrEqual(400)
  expect(track.height).toBeGreaterThanOrEqual(4)
  const thumbBox = (await thumb.boundingBox())!
  expect(thumbBox.width).toBeGreaterThanOrEqual(12)
  expect(thumbBox.height).toBeGreaterThanOrEqual(12)
  await thumb.focus()
  for (const [key, value] of [["ArrowRight", "2.25"], ["End", "10"], ["ArrowRight", "10"], ["Home", "0"], ["ArrowLeft", "0"], ["ArrowRight", "0.25"]]) {
    // Do not use Locator.press here: refocusing would hide a patch-induced focus loss.
    await page.keyboard.press(key)
    await expect(slider).toHaveAttribute("phx-value-values", `[${value}]`)
    await expect(thumb).toHaveAttribute("aria-valuenow", value)
    await expect(thumb).toBeFocused()
    expect(await formEntries(page, "#slider-external-form")).toEqual([["quantity", value]])
  }
  await openFixture(page, "slider-multiple-instances")
  const price = page.locator("#slider-price")
  const rating = page.locator("#slider-rating")
  const priceBox = (await price.boundingBox())!
  const ratingBox = (await rating.boundingBox())!
  expect(priceBox.width).toBeGreaterThanOrEqual(180)
  expect(ratingBox.width).toBeGreaterThanOrEqual(180)
  expect(ratingBox.y).toBeGreaterThanOrEqual(priceBox.y + priceBox.height + 8)
  await price.getByRole("slider").first().press("ArrowRight")
  await expect(price).toHaveAttribute("phx-value-values", "[6,15]")
  await expect(rating.getByRole("slider")).toHaveAttribute("aria-valuenow", "3")
  expect(await formEntries(page, "#slider-multiple-form")).toEqual([["price[]", "6"], ["price[]", "15"], ["rating", "3"]])
})

test("phoenix collapsible: independent disclosures support mouse and keyboard with real hidden content", async ({ page }) => {
  await openFixture(page, "collapsible-multiple-instances")
  const one = page.getByRole("button", { name: "One", exact: true })
  const two = page.getByRole("button", { name: "Two", exact: true })
  const first = page.getByText("First", { exact: true })
  const second = page.getByText("Second", { exact: true })
  await expect(one).toHaveAttribute("aria-expanded", "true")
  await expect(first).toBeVisible()
  await expect(two).toHaveAttribute("aria-expanded", "false")
  await expect(second).toBeHidden()
  await two.click()
  await expect(two).toHaveAttribute("aria-expanded", "true")
  await expect(second).toBeVisible()
  await expect(first).toBeVisible()
  const contentId = await two.getAttribute("aria-controls")
  expect(contentId).toBeTruthy()
  await expect(page.locator(`[id="${contentId}"]`)).toContainText("Second")
  await one.press("Space")
  await expect(one).toHaveAttribute("aria-expanded", "false")
  await expect(first).toBeHidden()
  await expect(second).toBeVisible()
  await two.press("Enter")
  await expect(two).toHaveAttribute("aria-expanded", "false")
  await expect(second).toBeHidden()
})

test("phoenix toggle-group: multiple selections persist and vertical single selection skips disabled items", async ({ page }) => {
  await openFixture(page, "toggle-group")
  const group = page.locator("#formatting")
  const bold = page.getByRole("button", { name: "Toggle bold", exact: true })
  const italic = page.getByRole("button", { name: "Toggle italic", exact: true })
  await bold.click()
  await expect(group).toHaveAttribute("phx-values", '["bold"]')
  await expect(bold).toHaveAttribute("aria-pressed", "true")
  await italic.click()
  await expect(group).toHaveAttribute("phx-values", '["bold","italic"]')
  await expect(bold).toHaveAttribute("aria-pressed", "true")
  await expect(italic).toHaveAttribute("aria-pressed", "true")
  await italic.press("Space")
  await expect(group).toHaveAttribute("phx-values", '["bold"]')
  await expect(italic).toHaveAttribute("aria-pressed", "false")
  await expect(bold).toHaveAttribute("aria-pressed", "true")

  await openFixture(page, "toggle-group-single-vertical")
  const left = page.getByRole("radio", { name: "Left", exact: true })
  const center = page.getByRole("radio", { name: "Center", exact: true })
  const right = page.getByRole("radio", { name: "Right", exact: true })
  await expect(center).toBeChecked()
  await expect(right).toBeDisabled()
  const leftBox = (await left.boundingBox())!
  const centerBox = (await center.boundingBox())!
  expect(leftBox.width).toBeGreaterThanOrEqual(24)
  expect(leftBox.width).toBeLessThanOrEqual(80)
  expect(centerBox.x).toBe(leftBox.x)
  expect(centerBox.y).toBeGreaterThanOrEqual(leftBox.y + leftBox.height - 1)
  await center.focus()
  await page.keyboard.press("ArrowUp")
  await expect(left).toBeFocused()
  await page.keyboard.press("Space")
  await expect(page.locator("#alignment")).toHaveAttribute("phx-values", '["left"]')
  await expect(left).toBeChecked()
  await expect(center).not.toBeChecked()
  await page.keyboard.press("ArrowUp")
  await expect(center).toBeFocused()
  await expect(right).not.toBeChecked()
})

test("phoenix radio-group: required keyboard selection skips disabled options and submits selected shipping", async ({ page }) => {
  await openFixture(page, "radio-group-required-vertical")
  const standard = page.getByRole("radio", { name: "Standard", exact: true })
  const express = page.getByRole("radio", { name: "Express", exact: true })
  const overnight = page.getByRole("radio", { name: "Overnight", exact: true })
  await expect(page.getByRole("radiogroup")).toHaveAttribute("aria-required", "true")
  await expect(standard).toBeChecked()
  await expect(express).toBeDisabled()
  await standard.focus()
  await page.keyboard.press("ArrowDown")
  await expect(page.locator("#shipping")).toHaveAttribute("phx-values", '["overnight"]')
  await expect(overnight).toBeChecked()
  await expect(overnight).toBeFocused()
  await expect(standard).not.toBeChecked()
  expect(await formEntries(page, "#shipping-form")).toEqual([["shipping", "overnight"]])
  await page.getByRole("button", { name: "Submit shipping" }).click()
  await expect(page.locator("#shipping-form output")).toHaveText("Submitted shipping: overnight")
  await standard.click()
  await expect(page.locator("#shipping")).toHaveAttribute("phx-values", '["standard"]')
  await expect(standard).toBeChecked()
  await expect(overnight).not.toBeChecked()
  await page.getByRole("button", { name: "Submit shipping" }).click()
  await expect(page.locator("#shipping-form output")).toHaveText("Submitted shipping: standard")
})

test("phoenix calendar: leap-day selection, month navigation, bounded ranges and seven-column layout", async ({ page }) => {
  await openFixture(page, "calendar-leap-selection")
  const grid = page.getByRole("grid", { name: "February 2024" })
  await expect(grid.locator("thead th")).toHaveCount(7)
  const rows = grid.locator("tbody tr")
  await expect(rows).toHaveCount(5)
  for (const row of await rows.all()) await expect(row.locator("td")).toHaveCount(7)
  const gridBox = (await grid.boundingBox())!
  expect(gridBox.width).toBeGreaterThanOrEqual(190)
  expect(gridBox.width).toBeLessThanOrEqual(500)
  const days = await rows.last().locator("td").evaluateAll(cells => cells.map(cell => {
    const rect = cell.getBoundingClientRect()
    return { x: rect.x, width: rect.width }
  }))
  for (let index = 0; index < days.length; index++) {
    expect(days[index].width).toBeGreaterThanOrEqual(24)
    expect(days[index].width).toBeLessThanOrEqual(60)
    if (index) expect(days[index].x).toBeGreaterThanOrEqual(days[index - 1].x + days[index - 1].width - 1)
  }
  await expect(grid.locator('[data-day="2024-02-29"]')).toHaveAttribute("aria-selected", "true")
  await page.getByRole("button", { name: "Wednesday, February 28th, 2024", exact: true }).click()
  await expect(grid.locator('[data-day="2024-02-28"]')).toHaveAttribute("aria-selected", "true")
  await expect(grid.locator('[data-day="2024-02-29"]')).not.toHaveAttribute("aria-selected", "true")
  await page.getByRole("button", { name: "Go to the Next Month" }).click()
  await expect(page.getByRole("grid", { name: "March 2024" })).toBeVisible()
  await page.getByRole("button", { name: "Go to the Previous Month" }).click()
  await expect(grid.locator('[data-day="2024-02-28"]')).toHaveAttribute("aria-selected", "true")

  await openFixture(page, "calendar-bounded-range")
  await expect(page.getByRole("button", { name: "Go to the Previous Month" })).toHaveAttribute("aria-disabled", "true")
  await expect(page.getByRole("button", { name: "Go to the Next Month" })).toHaveAttribute("aria-disabled", "true")
  await expect(page.getByRole("button", { name: "Sunday, February 4th, 2024", exact: true })).toBeDisabled()
  await expect(page.locator('td[aria-selected="true"]')).toHaveCount(3)
  await page.getByRole("button", { name: "Tuesday, February 20th, 2024", exact: true }).click()
  await expect(page.locator('[data-day="2024-02-20"]')).toHaveAttribute("aria-selected", "true")
  await expect(page.locator('td[aria-selected="true"]')).toHaveCount(11)
})

