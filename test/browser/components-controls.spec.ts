test("phoenix progress: accessible caller status, bounded fill geometry and upstream indeterminate semantics", async ({ page }) => {
  await openFixture(page, "progress-custom-class-aria")
  const upload = page.getByRole("progressbar", { name: "Upload", exact: true })
  await expect(upload).toHaveAttribute("aria-valuetext", "Uploading")
  await expect(upload).toHaveAttribute("aria-valuemin", "0")
  await expect(upload).toHaveAttribute("aria-valuemax", "100")
  // The canonical wrapper consumes value for its fill, not Radix Root's value prop.
  await expect(upload).toHaveAttribute("data-state", "indeterminate")
  await expect(upload).not.toHaveAttribute("aria-valuenow")
  const root = (await upload.boundingBox())!
  const indicator = (await upload.locator('[data-slot="progress-indicator"]').boundingBox())!
  expect(root.width).toBeGreaterThanOrEqual(150)
  expect(root.width).toBeLessThanOrEqual(260)
  expect(root.height).toBeGreaterThanOrEqual(4)
  expect(root.height).toBeLessThanOrEqual(12)
  expect(indicator.width).toBeCloseTo(root.width, 1)
  expect(indicator.x + indicator.width - root.x).toBeCloseTo(root.width * 0.75, 1)

  await openFixture(page, "progress-custom-max")
  const custom = page.getByRole("progressbar")
  await expect(custom).toHaveAttribute("aria-valuemax", "200")
  await expect(custom).not.toHaveAttribute("aria-valuenow")
  const customBox = (await custom.boundingBox())!
  const customFill = (await custom.locator('[data-slot="progress-indicator"]').boundingBox())!
  expect(customFill.x + customFill.width - customBox.x).toBeCloseTo(customBox.width * 0.5, 1)
  await openFixture(page, "progress-absent")
  const pending = page.getByRole("progressbar")
  await expect(pending).toHaveAttribute("data-state", "indeterminate")
  await expect(pending).not.toHaveAttribute("aria-valuenow")
  const pendingBox = (await pending.boundingBox())!
  const pendingFill = (await pending.locator('[data-slot="progress-indicator"]').boundingBox())!
  expect(pendingFill.x + pendingFill.width).toBeCloseTo(pendingBox.x, 1)
})
